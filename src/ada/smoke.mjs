import { Lucid, Emulator, generateEmulatorAccountFromPrivateKey, Data, Constr, validatorToAddress, getAddressDetails, CML, PROTOCOL_PARAMETERS_DEFAULT } from "@lucid-evolution/lucid";
import fs from "fs";
const bp = JSON.parse(fs.readFileSync("onchain/plutus.json"));
const script = { type: "PlutusV3", script: bp.validators.find(v => v.title === "escrow.escrow.spend").compiledCode };
const kp = JSON.parse(fs.readFileSync("mainnet_params_koios.json"));
const pp = { ...PROTOCOL_PARAMETERS_DEFAULT, maxTxExMem: BigInt(kp.maxTxExecutionUnits.memory), maxTxExSteps: BigInt(kp.maxTxExecutionUnits.steps),
  costModels: { ...PROTOCOL_PARAMETERS_DEFAULT.costModels, PlutusV3: kp.costModels.PlutusV3 } };
console.log("default V3 len", PROTOCOL_PARAMETERS_DEFAULT.costModels.PlutusV3.length);
const A = generateEmulatorAccountFromPrivateKey({ lovelace: 2_000_000_000n });
const B = generateEmulatorAccountFromPrivateKey({ lovelace: 200_000_000n });
const em = new Emulator([A, B], pp);
const lucid = await Lucid(em, "Custom");
const addr = validatorToAddress("Custom", script);
const pkh = a => getAddressDetails(a.address).paymentCredential.hash;
const t0 = em.now();
const T1 = t0 + 250_000, T2 = t0 + 350_000;
const datum = Data.to(new Constr(0, [pkh(A), pkh(B), "00".repeat(48), "00".repeat(48), BigInt(T1), BigInt(T2)]));
lucid.selectWallet.fromPrivateKey(A.privateKey);
const lock = await lucid.newTx().pay.ToContract(addr, { kind: "inline", value: datum }, { lovelace: 1_000_000_000n }).complete();
const h = await (await lock.sign.withWallet().complete()).submit();
em.awaitBlock(1);
console.log("locked", h, "fee", lock.toTransaction().body().fee());
em.awaitSlot(400);
lucid.selectWallet.fromPrivateKey(B.privateKey);
const [u] = await lucid.utxosAt(addr);
const tx = await lucid.newTx().collectFrom([u], Data.to(new Constr(2, []))).attach.SpendingValidator(script).addSignerKey(pkh(B)).validFrom(em.now()).complete();
const h2 = await (await tx.sign.withWallet().complete()).submit();
em.awaitBlock(1);
const t = tx.toTransaction(); const r = t.witness_set().redeemers().as_map_redeemer_key_to_redeemer_val();
console.log("punish", h2, "fee", t.body().fee(), "size", t.to_cbor_bytes().length, r ? "map" : "legacy");
console.log((await lucid.utxosAt(B.address)).map(u => u.assets.lovelace));
